const fs = require('fs');
const path = require('path');
const sqlite3 = require('sqlite3').verbose();

const root = path.resolve(__dirname, '..');
const dbPath = path.join(root, 'db.sqlite');
const mode = process.argv.includes('--apply') ? 'apply' : 'dry-run';
const generatedBy = 'scripts/build-compatibility-edges.js';

function openDb() {
  return new sqlite3.Database(dbPath);
}

function all(db, sql, params = []) {
  return new Promise((resolve, reject) => {
    db.all(sql, params, (err, rows) => (err ? reject(err) : resolve(rows)));
  });
}

function run(db, sql, params = []) {
  return new Promise((resolve, reject) => {
    db.run(sql, params, function onRun(err) {
      if (err) reject(err);
      else resolve(this);
    });
  });
}

function parseJson(value, fallback) {
  if (value == null || String(value).trim() === '') return fallback;
  try {
    return JSON.parse(value);
  } catch {
    return fallback;
  }
}

function asArray(value) {
  const parsed = parseJson(value, []);
  return Array.isArray(parsed) ? parsed.filter(Boolean) : [];
}

function makeEdgeKey(subject, relationship, object) {
  return `${subject}::${relationship}::${object}`;
}

function evidenceRefsFor(row) {
  return JSON.stringify([...new Set(asArray(row.sources).map((item) => String(item).trim()).filter(Boolean))]);
}

function componentTypeFor(id, nodes) {
  return nodes.get(id)?.component_type || null;
}

function addEdge(edges, edge) {
  const edgeKey = makeEdgeKey(edge.subject_json_id, edge.relationship, edge.object_json_id);
  if (edges.has(edgeKey)) return;
  edges.set(edgeKey, {
    edge_key: edgeKey,
    generated_by: generatedBy,
    ...edge,
  });
}

function buildEdges(tools, machines) {
  const nodes = new Map();
  for (const machine of machines) {
    nodes.set(machine.json_id, {
      json_id: machine.json_id,
      component_type: 'machine',
      row: machine,
    });
  }
  for (const tool of tools) {
    nodes.set(tool.json_id, {
      json_id: tool.json_id,
      component_type: tool.component_type,
      row: tool,
    });
  }

  const edges = new Map();

  for (const tool of tools) {
    if (tool.mounts_to) {
      addEdge(edges, {
        subject_json_id: tool.json_id,
        relationship: 'mounts_to',
        object_json_id: tool.mounts_to,
        subject_component_type: tool.component_type,
        object_component_type: componentTypeFor(tool.mounts_to, nodes),
        verification_status: 'needs_review',
        evidence_kind: 'existing_database',
        evidence_refs: evidenceRefsFor(tool),
        confidence: 0.6,
        notes: 'Imported from tools.mounts_to. Review against manufacturer catalog, machine manual, or shop-proven setup before marking verified.',
      });
    }

    for (const machineId of asArray(tool.compatible_machines)) {
      addEdge(edges, {
        subject_json_id: tool.json_id,
        relationship: 'compatible_with_machine',
        object_json_id: machineId,
        subject_component_type: tool.component_type,
        object_component_type: componentTypeFor(machineId, nodes),
        verification_status: 'needs_review',
        evidence_kind: 'existing_database',
        evidence_refs: evidenceRefsFor(tool),
        confidence: 0.5,
        notes: 'Imported from tools.compatible_machines after cleanup removed prose-only compatibility. Review before marking verified.',
      });
    }

    if (['holder', 'module'].includes(tool.component_type)) {
      for (const insertId of asArray(tool.compatible_inserts)) {
        addEdge(edges, {
          subject_json_id: tool.json_id,
          relationship: 'accepts_insert',
          object_json_id: insertId,
          subject_component_type: tool.component_type,
          object_component_type: componentTypeFor(insertId, nodes),
          verification_status: 'inferred',
          evidence_kind: 'iso_seat_match',
          evidence_refs: evidenceRefsFor(tool),
          confidence: 0.45,
          notes: 'Generated by matching holder/module insert_seat to insert iso_designation. Treat as unverified until checked against catalog or shop setup.',
        });
      }
    }
  }

  return { edges: [...edges.values()], nodes };
}

function validateEdges(edges, nodes) {
  const problems = [];
  const keys = new Set();
  const verifiedLike = new Set(['verified', 'shop_verified', 'catalog_claim']);

  for (const edge of edges) {
    if (keys.has(edge.edge_key)) problems.push({ edge_key: edge.edge_key, problem: 'duplicate edge key' });
    keys.add(edge.edge_key);

    if (!nodes.has(edge.subject_json_id)) problems.push({ edge_key: edge.edge_key, problem: 'missing subject node' });
    if (!nodes.has(edge.object_json_id)) problems.push({ edge_key: edge.edge_key, problem: 'missing object node' });

    const refs = parseJson(edge.evidence_refs, null);
    if (!Array.isArray(refs)) problems.push({ edge_key: edge.edge_key, problem: 'evidence_refs is not a JSON array' });
    if (verifiedLike.has(edge.verification_status) && (!Array.isArray(refs) || refs.length === 0)) {
      problems.push({ edge_key: edge.edge_key, problem: 'verified edge has no evidence_refs' });
    }

    if (edge.confidence < 0 || edge.confidence > 1) {
      problems.push({ edge_key: edge.edge_key, problem: 'confidence outside 0..1' });
    }
  }

  return problems;
}

async function ensureSchema(db) {
  await run(db, `
    CREATE TABLE IF NOT EXISTS compatibility_edges (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      edge_key TEXT UNIQUE NOT NULL,
      subject_json_id TEXT NOT NULL,
      relationship TEXT NOT NULL CHECK (relationship IN (
        'mounts_to',
        'compatible_with_machine',
        'accepts_insert'
      )),
      object_json_id TEXT NOT NULL,
      subject_component_type TEXT,
      object_component_type TEXT,
      verification_status TEXT NOT NULL CHECK (verification_status IN (
        'verified',
        'shop_verified',
        'catalog_claim',
        'inferred',
        'needs_review',
        'rejected'
      )),
      evidence_kind TEXT NOT NULL CHECK (evidence_kind IN (
        'manufacturer_catalog',
        'machine_manual',
        'shop_note',
        'existing_database',
        'iso_seat_match'
      )),
      evidence_refs TEXT NOT NULL DEFAULT '[]',
      confidence REAL NOT NULL CHECK (confidence >= 0 AND confidence <= 1),
      notes TEXT,
      generated_by TEXT NOT NULL DEFAULT 'manual',
      created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
      CHECK (
        verification_status NOT IN ('verified', 'shop_verified', 'catalog_claim')
        OR evidence_refs <> '[]'
      )
    )
  `);

  await run(db, 'CREATE INDEX IF NOT EXISTS idx_compat_edges_subject ON compatibility_edges(subject_json_id)');
  await run(db, 'CREATE INDEX IF NOT EXISTS idx_compat_edges_object ON compatibility_edges(object_json_id)');
  await run(db, 'CREATE INDEX IF NOT EXISTS idx_compat_edges_status ON compatibility_edges(verification_status)');
}

async function insertEdges(db, edges) {
  await run(db, 'BEGIN TRANSACTION');
  try {
    await run(db, 'DELETE FROM compatibility_edges WHERE generated_by = ?', [generatedBy]);
    const sql = `
      INSERT INTO compatibility_edges (
        edge_key,
        subject_json_id,
        relationship,
        object_json_id,
        subject_component_type,
        object_component_type,
        verification_status,
        evidence_kind,
        evidence_refs,
        confidence,
        notes,
        generated_by
      ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
      ON CONFLICT(edge_key) DO UPDATE SET
        subject_component_type = excluded.subject_component_type,
        object_component_type = excluded.object_component_type,
        verification_status = excluded.verification_status,
        evidence_kind = excluded.evidence_kind,
        evidence_refs = excluded.evidence_refs,
        confidence = excluded.confidence,
        notes = excluded.notes,
        generated_by = excluded.generated_by,
        updated_at = CURRENT_TIMESTAMP
    `;

    for (const edge of edges) {
      await run(db, sql, [
        edge.edge_key,
        edge.subject_json_id,
        edge.relationship,
        edge.object_json_id,
        edge.subject_component_type,
        edge.object_component_type,
        edge.verification_status,
        edge.evidence_kind,
        edge.evidence_refs,
        edge.confidence,
        edge.notes,
        edge.generated_by,
      ]);
    }
    await run(db, 'COMMIT');
  } catch (err) {
    await run(db, 'ROLLBACK');
    throw err;
  }
}

function summarize(edges, problems) {
  return {
    generated_edges: edges.length,
    by_relationship: edges.reduce((acc, edge) => {
      acc[edge.relationship] = (acc[edge.relationship] || 0) + 1;
      return acc;
    }, {}),
    by_status: edges.reduce((acc, edge) => {
      acc[edge.verification_status] = (acc[edge.verification_status] || 0) + 1;
      return acc;
    }, {}),
    by_evidence_kind: edges.reduce((acc, edge) => {
      acc[edge.evidence_kind] = (acc[edge.evidence_kind] || 0) + 1;
      return acc;
    }, {}),
    validation_problems: problems.length,
    validation_problem_sample: problems.slice(0, 20),
  };
}

async function main() {
  if (!fs.existsSync(dbPath)) throw new Error(`Missing database: ${dbPath}`);

  let backup = null;
  if (mode === 'apply') {
    const stamp = new Date().toISOString().replace(/[:.]/g, '-');
    backup = path.join(root, `db.sqlite.backup-edges-${stamp}`);
    fs.copyFileSync(dbPath, backup);
  }

  const db = openDb();
  const tools = await all(db, 'SELECT * FROM tools ORDER BY id');
  const machines = await all(db, 'SELECT * FROM machines ORDER BY id');
  const { edges, nodes } = buildEdges(tools, machines);
  const problems = validateEdges(edges, nodes);

  if (problems.length) {
    db.close();
    console.log(JSON.stringify({ mode, backup, ...summarize(edges, problems) }, null, 2));
    process.exitCode = 1;
    return;
  }

  if (mode === 'apply') {
    await ensureSchema(db);
    await insertEdges(db, edges);
  }

  const persisted = mode === 'apply'
    ? await all(db, 'SELECT relationship, verification_status, evidence_kind, COUNT(*) AS count FROM compatibility_edges GROUP BY relationship, verification_status, evidence_kind ORDER BY relationship, verification_status, evidence_kind')
    : [];

  db.close();

  console.log(JSON.stringify({ mode, backup, ...summarize(edges, problems), persisted }, null, 2));
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
